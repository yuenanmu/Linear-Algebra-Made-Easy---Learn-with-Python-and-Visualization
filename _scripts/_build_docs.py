def build_index():
    A = []
    P = A.append
    P('# 📚 内容索引：15 章 × 四种素材')
    P('')
    P('> [!info] 读法')
    P('> 每行的四个链接都能直接点开。**中文**和 **EN** 是同一内容的两份正文，PPT 是它的图形压缩版。')
    P('> 想看某一章的完整学习顺序（含自查清单和笔记区），点最右边那一列的章节卡。')
    P('')
    P('---')
    P('')
    for ch in CHAPTERS:
        num = int(ch)
        secs = SECS[ch]
        nbc = NBS[ch]
        P('## 第 %d 章 · %s' % (num, CH_ZH[ch]))
        P('')
        P('章节卡 → %s ｜ 代码 %d 个 ｜ 正文 %d 节 ｜ PPT %d 份' % (
            ch_link(ch), sum(len(v) for v in nbc.values()), len(secs),
            sum(1 for s in secs if PPT.get((ch, s)))))
        P('')
        P('| 小节 | 主题 | 中文正文 | English | PPT | 代码 |')
        P('| --- | --- | --- | --- | --- | --- |')
        for s in secs:
            k = (ch, s)
            zh = BODY[k].get('zh')
            en = BODY[k].get('en')
            p = PPT.get(k, {})
            got = nbc.get(s, [])
            c_zh = '[[%s|📖 中文]]' % zh if zh else '—'
            c_en = '[[%s|📘 EN]]' % en if en else '—'
            cells = []
            if p.get('zh'):
                cells.append('[[%s|中]]' % p['zh'])
            if p.get('en'):
                cells.append('[[%s|EN]]' % p['en'])
            c_ppt = ' '.join(cells) or '—'
            c_nb = '**%d 个**' % len(got) if got else '*无*'
            P('| %s-%s | %s | %s | %s | %s | %s |' % (ch, s, zh, c_zh, c_en, c_ppt, c_nb))
        P('')
        # 代码明细
        any_nb = any(nbc.get(s) for s in secs)
        if any_nb:
            P('<details><summary>💻 本章 notebook 明细（点开）</summary>')
            P('')
            for s in secs:
                got = nbc.get(s, [])
                if not got:
                    continue
                P('- **%s-%s %s**' % (ch, s, BODY[(ch, s)].get('zh', '')))
                for f, t in got:
                    P('    - [[代码/%s/%s|%s]]' % (DIR[ch], f, t))
            P('')
            P('</details>')
            P('')
    P('---')
    P('')
    P('返回 [[线性代数不难·导读|🏠 总览]]')
    P('')
    W(os.path.join('..', G, '01-内容索引.md'), '\n'.join(A))


